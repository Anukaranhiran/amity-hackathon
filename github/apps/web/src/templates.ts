export function templateSpec(id: TemplateId): string {
  switch (id) {
    case 'gemini': return geminiSpec();
    case 'openai': return openaiSpec();
    case 'github': return githubSpec();
    case 'stripe': return stripeSpec();
    default: throw new Error(`No generated contract for template "${id}"`);
  }
}
