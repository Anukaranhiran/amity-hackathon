const jsonResp = (description: string, schema?: Record<string, unknown>) => ({
  description,
  ...(schema ? { content: { 'application/json': { schema } } } : {}),
});

const errResp = jsonResp('Error envelope', {
  type: 'object',
  properties: { error: { type: 'object', properties: { message: { type: 'string' } } } },
});

function spec(opts: {
  title: string;
  description: string;
  securitySchemes: Record<string, unknown>;
  security: Array<Record<string, string[]>>;
  paths: Record<string, unknown>;
}): string {
  return JSON.stringify(
    {
      openapi: '3.0.3',
      info: {
        title: opts.title,
        description: opts.description,
        version: '1.0.0',
        'x-shulker-template': true,
      },
      servers: [],
      components: { securitySchemes: opts.securitySchemes },
      security: opts.security,
      paths: opts.paths,
    },
    null,
    2,
  );
}

