/**
 * Built-in API contract templates for the New Scan workflow.
 *
 * Each generator returns a VALID OpenAPI 3.0.3 JSON document (as a string)
 * that passes Shulker's spec validator and inventory import pipeline with
 * no file upload. Pure TypeScript — no React — so it is unit-testable from
 * scripts/e2e.mjs.
 */

export type TemplateId = 'gemini' | 'openai' | 'github' | 'stripe' | 'custom';

export interface TemplateMeta {
  id: TemplateId;
  label: string;
  description: string;
  target: string;
  authMode: 'api-key' | 'bearer';
  headerName?: string; // api-key mode only
  keyUrl: string; // where the user obtains a key
}

