/* Gemini — API key in x-goog-api-key header                           */
/* ------------------------------------------------------------------ */

export function geminiSpec(): string {
  const model = {
    type: 'object',
    properties: {
      name: { type: 'string' },
      displayName: { type: 'string' },
      supportedGenerationMethods: { type: 'array', items: { type: 'string' } },
    },
  };
  return spec({
    title: 'Google Gemini API (Generative Language)',
    description: 'Generated by Shulker — list models and generate content with an API key.',
    securitySchemes: { ApiKeyAuth: { type: 'apiKey', in: 'header', name: 'x-goog-api-key' } },
    security: [{ ApiKeyAuth: [] }],
    paths: {
      '/v1beta/models': {
        get: {
          operationId: 'listModels',
          summary: 'Lists available Gemini models',
          tags: ['Models'],
          parameters: [
            { name: 'pageSize', in: 'query', schema: { type: 'integer' } },
            { name: 'pageToken', in: 'query', schema: { type: 'string' } },
          ],
          responses: {
            '200': jsonResp('Model list', {
              type: 'object',
              properties: { models: { type: 'array', items: model } },
            }),
            '403': errResp,
          },
        },
      },
      '/v1beta/models/{model}': {
        get: {
          operationId: 'getModel',
          summary: 'Fetch a single model',
          tags: ['Models'],
          parameters: [{ name: 'model', in: 'path', required: true, schema: { type: 'string' } }],
          responses: { '200': jsonResp('Model', model), '404': errResp },
        },
      },
      '/v1beta/models/{model}:generateContent': {
        post: {
          operationId: 'generateContent',
          summary: 'Generate content from a prompt',
          tags: ['Generation'],
          parameters: [{ name: 'model', in: 'path', required: true, schema: { type: 'string' } }],
          requestBody: {
            required: true,
            content: {
              'application/json': {
                schema: {
                  type: 'object',
                  required: ['contents'],
                  properties: {
                    contents: {
                      type: 'array',
                      items: {
                        type: 'object',
                        properties: {
                          role: { type: 'string' },
                          parts: { type: 'array', items: { type: 'object', properties: { text: { type: 'string' } } } },
                        },
                      },
                    },
                  },
                },
              },
            },
          },
          responses: {
            '200': jsonResp('Generation result', {
              type: 'object',
              properties: {
                candidates: { type: 'array', items: { type: 'object', properties: { content: { type: 'object' } } } },
              },
            }),
            '400': errResp,
            '429': errResp,
          },
        },
      },
    },
  });
}

